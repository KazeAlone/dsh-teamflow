/** workflow-preview with TEAMFLOW_PREVIEW_REVIEW=1 and TEAMFLOW_PREVIEW_REPAIR=1. */
import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
const {chromium}=await import(process.env.TEAMFLOW_PLAYWRIGHT_MODULE??'playwright')
const browser=await chromium.launch({channel:'msedge',headless:true})
const output=resolve('output/review-continuation');mkdirSync(output,{recursive:true})
try {
 const page=await browser.newPage({viewport:{width:1440,height:1050}}),actions=[],errors=[]
 page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.url().endsWith('/workflow')&&r.method()==='POST')actions.push(r.postDataJSON())})
 await page.goto(process.env.TEAMFLOW_REVIEW_URL??'http://127.0.0.1:8378')
 await page.getByRole('button',{name:'验收 · 功能交付验收 ↗',exact:true}).click()
 const review=page.locator('[data-review-workbench]')
 await review.getByRole('textbox',{name:'验收意见',exact:true}).fill('请修复导出编码')
 await review.getByRole('button',{name:'退回修改',exact:true}).click()
 await review.getByRole('button',{name:'重新验收当前结果',exact:true}).waitFor()
 assert.equal(await review.getByRole('textbox',{name:'返工要求',exact:true}).inputValue(),'请修复导出编码')
 await page.screenshot({path:resolve(output,'returned.png')})
 await review.getByRole('combobox',{name:'验收轮次',exact:true}).selectOption('0')
 assert.equal(await review.getByRole('button',{name:'重新验收当前结果',exact:true}).count(),0)
 await review.getByRole('combobox',{name:'验收轮次',exact:true}).selectOption('current')
 await review.getByRole('button',{name:'重新验收当前结果',exact:true}).click()
 await review.getByRole('button',{name:'通过验收',exact:true}).click()
 await review.getByRole('button',{name:'确认通过',exact:true}).click()
 await review.getByText('已保存的验收决定 · 通过',{exact:true}).waitFor()
 assert.equal(actions.filter(a=>['edit','resume_rerun_path','open_discussion'].includes(a.action)).length,0)
 // The other checkpoint exercises actual repair and preserves the first checkpoint's approval history.
 await page.getByRole('button',{name:'验收 · 独立检查点',exact:true}).click()
 await review.getByRole('textbox',{name:'验收意见',exact:true}).fill('修复后重新验证')
 await review.getByRole('button',{name:'退回修改',exact:true}).click()
 await review.getByRole('textbox',{name:'返工要求',exact:true}).fill('补充中文编码修复和测试')
 await review.getByRole('button',{name:'保存要求并重跑任务',exact:true}).click()
 await review.getByRole('button',{name:'运行到此节点',exact:true}).click()
 // Stay in the panel: new-round evidence must load without a manual refresh.
 await review.getByRole('button',{name:'通过验收',exact:true}).waitFor()
 await review.getByText('模拟重跑结果：已按最新要求重新执行。',{exact:true}).waitFor()
 await review.getByRole('button',{name:'通过验收',exact:true}).click()
 await review.getByRole('button',{name:'确认通过',exact:true}).click()
 await review.getByText('已保存的验收决定 · 通过',{exact:true}).waitFor()
 const state=await page.request.post(new URL('/plugins/dsh-agent-teams/workflow',page.url()).href,{data:{action:'state',sessionId:'preview',teamId:'preview'}}).then(r=>r.json())
 assert.equal(state.team.tasks.find(t=>t.id==='t4').checkpoint.decision,'approve')
 assert.equal(state.team.tasks.find(t=>t.id==='t2').workflowPaused,true)
 assert.equal(state.team.tasks.find(t=>t.id==='t3').workflowPaused,true)
 assert.ok(state.team.tasks.find(t=>t.id==='t2').checkpoint.history.some(h=>h.decision==='reject'))
 assert.equal(actions.filter(a=>a.action==='edit').length,1)
 assert.equal(actions.find(a=>a.action==='edit').operations[0].instructions,'补充中文编码修复和测试')
 assert.equal(actions.filter(a=>a.action==='open_discussion').length,0)
 assert.equal(actions.filter(a=>a.action==='materials').length,3,'Each ready review round must load once, without manual refresh or poll loops')
 await page.screenshot({path:resolve(output,'repaired-approved.png')})
 assert.deepEqual(errors,[])
 console.log('PASS returned → reopen → approve; returned → repair → resume path → refreshed evidence → approve; history and sibling pauses retained')
} finally {await browser.close()}
