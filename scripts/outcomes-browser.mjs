/** Run workflow-preview.mjs with TEAMFLOW_PREVIEW_OUTCOMES=1. No provider calls. */
import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
const { chromium } = await import(process.env.TEAMFLOW_PLAYWRIGHT_MODULE ?? 'playwright')
const output=resolve('output/outcome-showcase');mkdirSync(output,{recursive:true})
const browser=await chromium.launch({channel:process.env.TEAMFLOW_BROWSER_CHANNEL??'msedge',headless:true})
try {
  const page=await browser.newPage({viewport:{width:1440,height:1050}}),actions=[],errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  page.on('request',r=>{if(r.url().endsWith('/workflow')&&r.method()==='POST')actions.push(r.postDataJSON().action)})
  await page.goto(process.env.TEAMFLOW_OUTCOME_URL??'http://127.0.0.1:8377')
  await page.getByRole('button',{name:'验收 · 需求人工验收 ↗',exact:true}).click()
  await page.getByRole('button',{name:'交付内容',exact:true}).click()
  const showcase=page.getByRole('region',{name:'交付内容',exact:true})
  await showcase.getByText('6 tests passed',{exact:true}).waitFor()
  await showcase.getByText('历史提交说明',{exact:false}).click()
  await showcase.getByText('上一轮：编码待修复。',{exact:true}).waitFor()
  await page.screenshot({path:resolve(output,'submissions.png')})
  await showcase.getByRole('button',{name:/report.md.*约定交付物/}).click()
  await showcase.getByRole('heading',{name:'CSV 导出交付'}).waitFor()
  assert.equal(await page.evaluate(()=>window.previewExecuted),undefined)
  assert.equal(await showcase.locator('script,iframe').count(),0)
  await showcase.getByRole('button',{name:'查看原文',exact:true}).click()
  await showcase.locator('pre').filter({hasText:'# CSV 导出交付'}).waitFor()
  await showcase.getByRole('button',{name:/orders.csv.*约定交付物/}).click()
  await showcase.getByRole('cell',{name:'正常订单',exact:true}).waitFor()
  assert.equal(await showcase.getByRole('cell',{name:'含逗号,引号"与换行\n第二行',exact:true}).count(),1)
  await page.screenshot({path:resolve(output,'csv-light.png')})
  await page.emulateMedia({colorScheme:'dark'});await page.evaluate(()=>document.documentElement.style.colorScheme='dark')
  await page.screenshot({path:resolve(output,'csv-dark.png')})
  await showcase.getByRole('button',{name:/missing.md.*约定交付物/}).click()
  await showcase.getByText('文件不存在或已被移除',{exact:true}).waitFor()
  await showcase.getByRole('button',{name:/preview.png.*约定交付物/}).click()
  await showcase.getByRole('img').waitFor();await page.waitForFunction(()=>document.querySelector('img[alt="preview.png"]')?.complete)
  assert.ok(await showcase.getByRole('img').evaluate(img=>img.naturalWidth>0))
  await showcase.getByRole('button',{name:'查看原任务',exact:true}).click()
  assert.equal(await showcase.count(),0)
  await page.getByRole('button',{name:'交付内容',exact:true}).click()
  await showcase.getByRole('button',{name:/需求人工验收/}).click()
  await page.locator('[data-review-workbench]').waitFor()
  // The preview itself never requests discussion/model actions or mutations.
  assert.ok(actions.every(a=>['state','outcome_preview','materials'].includes(a)),JSON.stringify(actions))
  await page.getByRole('button',{name:'交付内容',exact:true}).click()
  await page.getByRole('combobox',{name:'Preview language'}).selectOption('en')
  await page.getByRole('region',{name:'Deliverables'}).waitFor()
  await page.setViewportSize({width:720,height:900})
  await page.screenshot({path:resolve(output,'narrow-en.png')})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  assert.deepEqual(errors,[])
  console.log('PASS outcome navigation, safe Markdown, CSV, image, missing file, history, locales, responsive layout, and no model actions')
} finally {await browser.close()}
