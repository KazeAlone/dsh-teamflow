/** Run against workflow-preview.mjs with TEAMFLOW_PREVIEW_REVIEW=1; no provider calls. */
import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
const { chromium } = await import(process.env.TEAMFLOW_PLAYWRIGHT_MODULE ?? 'playwright')
const output = resolve(process.env.TEAMFLOW_REVIEW_SCREENSHOTS ?? 'output/review-workbench')
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ channel: process.env.TEAMFLOW_BROWSER_CHANNEL ?? 'msedge', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } })
  const errors = [], actions = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (r.url().endsWith('/workflow') && r.method() === 'POST') actions.push(r.postDataJSON()) })
  await page.goto(process.env.TEAMFLOW_REVIEW_URL ?? 'http://127.0.0.1:8376')
  await page.getByRole('button', { name: '验收 · 功能交付验收 ↗', exact: true }).click()
  const review = page.locator('[data-review-workbench]')
  await review.getByRole('button', { name: '退回修改', exact: true }).waitFor()
  await review.getByRole('button', { name: '返回节点', exact: true }).click()
  await page.getByRole('button', { name: '开始验收', exact: true }).click()
  await review.getByRole('button', { name: /中文与特殊字符/ }).click()
  await page.getByText('UTF-8 BOM 与引号、逗号、换行往返读取通过。', { exact: true }).waitFor()
  await review.getByRole('button', { name: '与上一轮对比', exact: true }).click()
  await review.getByText('中文编码验证缺失。', { exact: true }).waitFor()
  await review.getByRole('textbox', { name: '验收意见', exact: true }).fill('保留本检查点意见')
  await review.getByRole('combobox', { name: '验收轮次' }).selectOption('0')
  assert.equal(await review.getByRole('button', { name: '通过验收', exact: true }).count(), 0)
  await review.getByText('请补充编码和大数据量验证。', { exact: true }).waitFor()
  await review.getByRole('combobox', { name: '验收轮次' }).selectOption('current')
  assert.equal(await review.getByRole('textbox', { name: '验收意见', exact: true }).inputValue(), '保留本检查点意见')
  await page.getByRole('combobox', { name: '其他待处理事项', exact: true }).selectOption({ label: '验收 · 独立检查点' })
  assert.equal(await review.getByRole('textbox', { name: '验收意见', exact: true }).inputValue(), '')
  await page.getByRole('button', { name: '验收 · 功能交付验收', exact: true }).click()
  assert.equal(await review.getByRole('textbox', { name: '验收意见', exact: true }).inputValue(), '保留本检查点意见')
  assert.equal(actions.filter(a => a.action === 'open_discussion').length, 0, 'Inspecting evidence must not start a model turn')
  await page.getByRole('button', { name: '放大面板', exact: true }).click()
  await page.screenshot({ path: resolve(output, 'expanded.png') })
  await page.getByRole('button', { name: '还原面板', exact: true }).click()
  await page.screenshot({ path: resolve(output, 'canvas-review.png') })
  await page.getByRole('combobox', { name: 'Preview language' }).selectOption('en')
  await review.getByRole('button', { name: 'Approve review', exact: true }).waitFor()
  await page.screenshot({ path: resolve(output, 'english.png') })
  await page.getByRole('combobox', { name: 'Preview language' }).selectOption('zh')
  await page.setViewportSize({ width: 600, height: 900 })
  await page.getByRole('button', { name: '修改与验收', exact: true }).click()
  assert.equal(await review.evaluate(el => el.scrollWidth <= el.clientWidth + 1), true)
  await page.screenshot({ path: resolve(output, 'narrow.png') })
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.emulateMedia({ colorScheme: 'dark' })
  // The preview pins a root color scheme, as the host does; update that fixture setting too.
  await page.evaluate(() => { document.documentElement.style.colorScheme = 'dark' })
  assert.equal(await review.evaluate(el => el.scrollWidth <= el.clientWidth + 1), true, 'Desktop review panel must not overflow')
  await page.screenshot({ path: resolve(output, 'dark.png') })
  await review.getByRole('textbox', { name: '验收意见', exact: true }).fill('')
  await review.getByRole('button', { name: '退回修改', exact: true }).click()
  await review.getByRole('alert').filter({ hasText: '请填写退回原因。' }).waitFor()
  assert.equal(actions.filter(a => a.action === 'review').length, 0)
  await review.getByRole('button', { name: '通过验收', exact: true }).click()
  await review.getByRole('button', { name: '继续检查', exact: true }).click()
  assert.equal(actions.filter(a => a.action === 'review').length, 0)
  await review.getByRole('textbox', { name: '验收意见', exact: true }).fill('请补充目标规模的实测。')
  await review.getByRole('button', { name: '退回修改', exact: true }).click()
  await review.getByText('已保存的验收决定 · 退回', { exact: true }).waitFor()
  assert.equal(actions.filter(a => a.action === 'review').length, 1)
  const state = await page.request.post(new URL('/plugins/dsh-agent-teams/workflow', page.url()).href, { data: { action: 'state', sessionId: 'preview', teamId: 'preview' } }).then(r => r.json())
  const gate = state.team.tasks.find(t => t.id === 't2')
  assert.equal(gate.checkpoint.decision, 'reject')
  assert.ok(gate.checkpoint.history.at(-1).materials)
  assert.equal(state.team.tasks.find(t => t.id === 't3').status, 'pending')
  await page.getByRole('button', { name: '验收 · 独立检查点', exact: true }).click()
  await review.getByRole('button', { name: '通过验收', exact: true }).click()
  await review.getByRole('button', { name: '确认通过', exact: true }).click()
  await review.getByText('已保存的验收决定 · 通过', { exact: true }).waitFor()
  assert.equal(actions.filter(a => a.action === 'review').length, 2)
  assert.deepEqual(errors, [])
  console.log('Review UI passed: entry, evidence, history, note isolation, no automatic model turn, expansion, locales, narrow/dark layout, confirmation and rejection.')
} finally { await browser.close() }
